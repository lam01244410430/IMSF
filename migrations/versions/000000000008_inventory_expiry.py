def _roles():
    bind = op.get_bind()
    names = []
    for variable in ("FINANCE_RUNTIME_ROLE", "INVENTORY_EXPIRY_WORKER_ROLE"):
        name = os.environ.get(variable)
        if not name:
            raise RuntimeError(f"{variable} must explicitly name an existing non-owner role")
        eligible = bind.execute(sa.text("""SELECT NOT(r.rolsuper OR r.rolcreaterole OR r.rolcreatedb OR r.rolbypassrls)
            AND NOT pg_has_role(r.rolname,current_user,'MEMBER')
            AND NOT has_schema_privilege(r.rolname,'public','CREATE')
            AND NOT EXISTS(SELECT 1 FROM pg_class c WHERE c.relnamespace='public'::regnamespace AND c.relowner=r.oid)
            FROM pg_roles r WHERE r.rolname=:role"""), {"role": name}).scalar()
        if eligible is not True:
            raise RuntimeError(f"{variable} must exist and be an unprivileged non-owner role")
        names.append(name)
    if names[0] == names[1] or bind.execute(sa.text(
        "SELECT pg_has_role(:worker,:runtime,'MEMBER') OR pg_has_role(:runtime,:worker,'MEMBER')"
    ), {"runtime": names[0], "worker": names[1]}).scalar():
        raise RuntimeError("INVENTORY_EXPIRY_WORKER_ROLE must be distinct and separate from FINANCE_RUNTIME_ROLE")
    if bind.execute(sa.text("""SELECT EXISTS(SELECT 1 FROM pg_auth_members m
        JOIN pg_roles r ON r.oid=m.member WHERE r.rolname=:role)"""), {"role": names[1]}).scalar():
        raise RuntimeError("INVENTORY_EXPIRY_WORKER_ROLE must have no role memberships, including NOINHERIT SET ROLE paths")
    if bind.execute(sa.text("""SELECT EXISTS(SELECT 1 FROM pg_class c
        WHERE c.relnamespace='public'::regnamespace AND c.relkind IN ('r','p')
        AND c.relname NOT IN ('scheduled_jobs','expiration_alerts')
        AND (has_table_privilege(:role,c.oid,'INSERT,UPDATE,DELETE,TRUNCATE')
            OR has_any_column_privilege(:role,c.oid,'INSERT,UPDATE')))"""), {"role": names[1]}).scalar():
        raise RuntimeError("INVENTORY_EXPIRY_WORKER_ROLE must have no existing business-table write privileges")
    return tuple(bind.dialect.identifier_preparer.quote(name) for name in names)


