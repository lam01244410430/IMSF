"""Import the 186 seed recipes (Option B, Lam 2026-11-22) into IMSF.

Reads the two QC-passed JSON batches -- ``monngonmoingay-100.json``
(86 Vietnamese recipes) and ``meishichina-100.json`` (100 Chinese
recipes) -- and inserts one ``community_recipes`` row per recipe plus
one ``recipe_ingredients`` row per ingredient line (1,925 lines
total). Run against a scratch database first; the live ``imsf`` run
is a separate, Lam-approved step.

Usage (from the repo root)::

    python3 scripts/import_recipes.py --vn /tmp/imsf-recipes/monngonmoingay-100.json \\
        --cn /tmp/imsf-recipes/meishichina-100.json \\
        --db-url postgresql+psycopg://imsf_v2:...@127.0.0.1:55434/imsf_test_p307_import

``--db-url`` defaults to the ``DATABASE_URL`` environment variable.
``--dry-run`` resolves and prints everything, then rolls back.
``--force`` deletes any recipes already present with the same
``source_url`` (and their ingredients, via the FK cascade) before
re-importing; without it the script REFUSES to run twice against the
same database (idempotency guard on ``source_url``).

DECISIONS (recorded here so a later reader can audit them):

* ``unit`` is ``NOT NULL`` on ``recipe_ingredients``. Any line whose
  unit cannot be split gets ``""`` (empty string) -- NEVER an invented
  unit. The same applies to ``amount``: lines with no amount get
  ``NULL``, never a guessed number. A quantity word with no number
  (``适量`` / ``少许`` / ``几片`` / ...) is stripped and also yields
  ``NULL`` / ``""``.
* Canonical matching REUSES the system's existing code
  (``app.reconcile.resolve_canonical`` with ``load_master_map`` /
  ``load_alias_map`` from ``worker.main``); there is no Qwen suggestion
  for recipes, so ``suggested=None``. Unmatched lines keep
  ``canonical_ingredient_id = NULL`` -- never an invented canonical.
  Only 20 master ingredients are seeded, so the match rate is low
  (see the run summary); that is expected, not a defect.
* ``cook_time`` (Chinese recipes only) uses a fixed map and NOTHING
  else: ``半小时`` -> 30, ``廿分钟`` -> 20, ``一小时`` -> 60,
  ``十分钟`` -> 10, ``三刻钟`` -> 45. Any other string (``数小时``,
  ``一天``, ``数天``, empty, or anything unseen) -> ``NULL`` plus a
  warning line in the output. Vietnamese recipes have no cook time in
  the source, so ``cook_time`` stays ``NULL`` -- never invented.
* ``steps_json`` is a JSON list of strings: ``prep_steps`` +
  ``cook_steps`` for Vietnamese recipes, ``cook_steps`` only for
  Chinese ones (their ``prep_steps`` are empty). ``serving`` is NOT
  stored -- there is no column for it.
* ``is_main_ingredient`` is true only for Chinese lines in the
  ``主料`` group, false otherwise (including all Vietnamese lines,
  which have no groups).
* ``author_id`` is ``NULL`` and ``status`` is ``'published'`` for
  every imported recipe. The Chinese source author name goes in the
  ``author`` TEXT column (exposed as ``author_name`` by the API);
  Vietnamese recipes have no author in the source, so ``NULL``.
* The id <-> source_url mapping is written to
  ``scripts/recipe_id_mapping.json`` (next to this script). It is
  generated by the TEST run, so its uuids belong to the test database;
  the live run will produce different uuids -- see the ``note`` field
  in that file.
"""

import argparse
import json
import re
import sys
from collections import Counter, defaultdict
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.reconcile import resolve_canonical  # noqa: E402

COOK_TIME_MAP = {
    "半小时": 30,
    "廿分钟": 20,
    "一小时": 60,
    "十分钟": 10,
    "三刻钟": 45,
}

# Units that select WHICH number in a line is the quantity. This is a
# selection preference only, NOT an allowlist: when no candidate has a
# known unit, the first number+token candidate is still kept, so an
# unknown trailing unit is never dropped. Length units (cm/mm) and
# time units (phút) are deliberately absent: "Cắt khúc 5cm" is a cut
# size, not a quantity.
KNOWN_UNITS = {
    # Vietnamese
    "g", "gr", "kg", "mg", "ml", "l", "lít", "cái", "quả", "trái", "củ",
    "cây", "nhánh", "lá", "miếng", "lát", "tép", "con", "hạt", "gói",
    "hũ", "cọng", "tai", "chén", "bát", "muỗng", "M", "m", "thìa", "lon",
    "hộp", "chai", "túi", "bịch", "bó", "nải", "khoanh", "viên", "giọt",
    "tô", "đĩa", "cup", "tbsp", "tsp",
    # Chinese
    "克", "毫升", "ML", "个", "只", "条", "根", "把", "颗", "片", "块",
    "粒", "头", "棵", "瓶", "包", "张", "段", "瓣", "碗", "杯", "袋",
    "盒", "罐", "盘", "勺", "小勺", "大勺", "汤匙", "茶匙", "匙", "小匙",
    "撮", "滴", "升", "斤", "两", "钱", "枝", "朵",
}

CN_NUMERALS = {
    "一": 1, "二": 2, "三": 3, "四": 4, "五": 5,
    "六": 6, "七": 7, "八": 8, "九": 9, "十": 10,
    "半": Decimal("0.5"), "两": 2,
}
# Units allowed after a Chinese-numeral amount ("料酒一勺" -> 1/勺).
# Longest first so "小勺" wins over "勺".
CN_NUMERAL_UNITS = (
    "小勺", "大勺", "汤匙", "茶匙", "小匙", "毫升",
    "勺", "匙", "个", "只", "条", "根", "把", "颗", "片",
    "块", "粒", "头", "棵", "瓶", "包", "张", "段", "瓣",
    "碗", "杯", "袋", "盒", "罐", "克", "g", "ml",
)

_PAREN_RE = re.compile(r"\s*[\(（][^\)）]*[\)）]")
_NUM_RE = re.compile(r"(\d+(?:[.,]\d+)?|\d+\s*/\s*\d+)\s*([^\s\d,，;；/]{1,6})")
_BARE_NUM_RE = re.compile(r"(\d+(?:[.,]\d+)?|\d+\s*/\s*\d+)\s*$")
_RANGE_RE = re.compile(
    r"(\d+(?:[.,]\d+)?)\s*[-~～]\s*(\d+(?:[.,]\d+)?)\s*([^\s\d,，;；/]{1,6})")
_CN_NUM_RE = re.compile(
    r"^(.*?)([一二三四五六七八九十半两])(" + "|".join(CN_NUMERAL_UNITS) + r")$")
_QTY_RE = re.compile(r"(适量|少许|若干|可选|几[^\s]{1,2})$")
_DANGLING_PER_UNIT_RE = re.compile(r"\s*\d+\s*\S*/\s*$")

MAX_AMOUNT = Decimal("99999999.99")  # numeric(10, 2)


def parse_cook_time(value):
    """Map a Chinese cook-time string to minutes, or None.

    Only the five strings in COOK_TIME_MAP have a number. Anything
    else (``数小时``, ``一天``, ``数天``, empty, unseen) is None --
    never a guessed number. The caller warns on unknown non-empty
    strings.
    """
    if value is None:
        return None
    return COOK_TIME_MAP.get(str(value).strip())


def _parse_number(token):
    """Decimal with 2 places + whether it was rounded to fit.

    ',' is a decimal separator ('1,5l' -> 1.5). Fractions ('1/3')
    round half-up to 2 places (0.33) and report rounded=True; exact
    fractions ('1/2' -> 0.50) and plain decimals report False.
    """
    token = token.replace(",", ".").strip()
    if "/" in token:
        num, den = token.split("/", 1)
        exact = Decimal(num.strip()) / Decimal(den.strip())
    else:
        exact = Decimal(token)
    value = exact.quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)
    return value, exact != value


def _clean_raw(raw):
    raw = raw.strip().rstrip(" -–")
    if raw.endswith("/"):
        # Dangling per-unit fragment, e.g. "Tôm sú size 50 con/".
        raw = _DANGLING_PER_UNIT_RE.sub("", raw).strip()
    return raw


def split_ingredient(line):
    """Split one ingredient line -> (raw_name, amount, unit, notes).

    ``amount`` is a Decimal with 2 places or None; ``unit`` is "" when
    no unit could be split (never invented). Rules, in order:

    1. Strip every parenthetical note "(...)" / "（...）" anywhere.
    2. ``Name: amount unit`` (colon + amount tail) splits at the
       colon; ``Name: A, B, C`` (composite list, tail starts with a
       word) keeps the WHOLE line as raw_name with NULL / "".
    3. Ranges ("30-40g", "5-6片", "30~40g") take the LOWER bound.
    4. Otherwise the FIRST number whose following token is a known
       unit wins ("Bánh tráng 3 màu 200g" -> 200/g, not 3/màu;
       "Cải bó xôi 150g ... 5cm" -> 150/g, not 5/cm). A candidate is
       skipped when it is part of a per-unit spec ("50 con/kg" and
       "con/1kg" -- "Tôm sú size 50 con/1kg 200g" -> 200/g) or when it
       would leave an empty raw_name ("1 con cá ... 600g" -> 600/g).
       With no known-unit candidate, the first number+token candidate
       is kept as-is (unknown units are never dropped).
    5. A trailing bare number ("红枣500") is an amount with unit "".
    6. A trailing Chinese numeral + unit ("料酒一勺" -> 1/勺,
       "贝贝南瓜半个" -> 0.5/个, "小米辣四个" -> 4/个).
    7. A trailing quantity word with no number ("葱适量", "鸡精少许",
       "香叶几片", "鸡精可选") strips the word -> NULL / "".
    8. Otherwise the whole line is the raw_name, NULL / "".
    Trailing preparation notes after the unit ("2 trái Cắt múi cau",
    "100g Cắt dầy 1,5cm") are dropped; the unit is the single token
    right after the number ("1 chén nhỏ" -> unit "chén").
    """
    notes = []
    s = _PAREN_RE.sub("", line or "").strip()
    if not s:
        return ("", None, "", ["empty line"])
    name_part = None
    rest = s
    if ":" in s or "：" in s:
        parts = re.split(r"[:：]", s, maxsplit=1)
        head, tail = parts[0], parts[1].strip()
        if re.match(r"^\d", tail) or (tail and tail[0] in CN_NUMERALS):
            name_part, rest = head.strip(), tail
        else:
            return (s, None, "", ["composite colon line"])
    base = name_part if name_part is not None else rest

    def _before(match):
        return _clean_raw(
            name_part if name_part is not None else rest[:match.start()])

    m = _RANGE_RE.search(rest)
    if m and m.group(3) in KNOWN_UNITS:
        amount, _rounded = _parse_number(m.group(1))
        return (_before(m), amount, m.group(3)[:20],
                notes + ["range lower bound"])
    candidates = list(_NUM_RE.finditer(rest))
    def _usable(cand):
        # Skip a per-unit spec on either side: "50 con/kg" (unit
        # followed by "/") and "con/1kg" (number preceded by "/").
        if cand.start() > 0 and rest[cand.start() - 1] == "/":
            return False
        end = cand.end()
        if end < len(rest) and rest[end] == "/":
            return False
        return bool(_before(cand))

    chosen = None
    for cand in candidates:
        if _usable(cand) and cand.group(2) in KNOWN_UNITS:
            chosen = cand
            break
    if chosen is None:
        for cand in candidates:
            if _usable(cand):
                chosen = cand
                break
    if chosen is not None:
        unit = chosen.group(2)
        if len(unit) > 20:
            notes.append("unit truncated to 20 chars")
            unit = unit[:20]
        amount, rounded = _parse_number(chosen.group(1))
        if rounded:
            notes.append("rounded to 2dp")
        return (_before(chosen), amount, unit, notes)
    m = _BARE_NUM_RE.search(rest)
    if m and _before(m):
        amount, _rounded = _parse_number(m.group(1))
        return (_before(m), amount, "", notes)
    m = _CN_NUM_RE.match(rest)
    if m and m.group(1).strip():
        value = CN_NUMERALS[m.group(2)]
        amount = value if isinstance(value, Decimal) else Decimal(value)
        raw = m.group(1).strip()
        if name_part is not None:
            raw = name_part
        return (raw, amount, m.group(3), notes + ["chinese numeral"])
    m = _QTY_RE.search(rest)
    if m:
        raw = _clean_raw(name_part if name_part is not None
                         else rest[:m.start()])
        if raw:
            return (raw, None, "", notes + ["quantity word, no number"])
    return (_clean_raw(base), None, "", notes)


def build_recipe_row(recipe, language):
    """Pure row builder: source recipe dict -> community_recipes columns.

    ``language`` is 'vi' or 'zh'. No DB access, so it is unit-testable.
    """
    is_zh = language == "zh"
    description = (recipe.get("description") or "").strip() or None
    # VN: prep + cook steps; CN: cook steps only (prep_steps are empty).
    if is_zh:
        steps = list(recipe.get("cook_steps") or [])
    else:
        steps = list(recipe.get("prep_steps") or []) + list(
            recipe.get("cook_steps") or [])
    return {
        "title": recipe["name"],
        "cover_image": recipe.get("image_url") or None,
        "language": language,
        "category": recipe.get("category") or None,
        "description": description,
        "source_url": recipe.get("source_url") or None,
        "slug": recipe.get("slug") or None,
        "difficulty": recipe.get("difficulty") if is_zh else None,
        "taste": recipe.get("taste") if is_zh else None,
        "author": recipe.get("author") if is_zh else None,
        "cook_time": parse_cook_time(recipe.get("cook_time"))
        if is_zh else None,
        "steps_json": json.dumps(steps, ensure_ascii=False),
    }


def _main_group_map(recipe):
    """Flat ingredient line -> is_main for Chinese recipes.

    Walks the flat ``ingredients`` list and consumes group membership
    counters (主料 first), so a line that appears in two groups keeps
    the 主料 flag on its first occurrence. No line is both 主料 and
    another group in the current data (verified), so this is exact
    there. Vietnamese recipes have no groups -> all False.
    """
    groups = recipe.get("ingredient_groups") or {}
    remaining = {g: Counter(v) for g, v in groups.items()}
    flags = []
    for line in recipe.get("ingredients") or []:
        is_main = False
        for group in ("主料", "辅料", "调料"):
            if remaining.get(group, Counter())[line] > 0:
                remaining[group][line] -= 1
                is_main = group == "主料"
                break
        flags.append(is_main)
    return flags


def run_import(vn_path, cn_path, db_url, *, dry_run=False, force=False,
               mapping_path=None):
    """Import both files. Returns the run summary dict."""
    # Lazy import: importing worker.main pulls redis/qwen/rag; the pure
    # functions above must stay importable without those.
    from worker.main import load_alias_map, load_master_map

    import sqlalchemy as sa
    from sqlalchemy import text

    with open(vn_path, encoding="utf-8") as fh:
        vn_recipes = json.load(fh)
    with open(cn_path, encoding="utf-8") as fh:
        cn_recipes = json.load(fh)
    jobs = [(r, "vi") for r in vn_recipes] + [(r, "zh") for r in cn_recipes]
    source_urls = [r.get("source_url") for r, _ in jobs]

    stats = {
        "recipes": Counter(),
        "ingredients": Counter(),
        "buckets": defaultdict(Counter),  # language -> bucket -> n
        "matched": 0,
        "unmatched": 0,
        "cook_time": Counter(),
        "warnings": [],
        "rounded_amounts": 0,
    }
    mapping = []
    engine = sa.create_engine(db_url)
    with engine.begin() as conn:
        master_map = load_master_map(conn)
        alias_map = load_alias_map(conn, master_map)
        existing = conn.execute(
            text("SELECT source_url FROM community_recipes"
                 " WHERE source_url = ANY(:urls)"),
            {"urls": source_urls},
        ).scalars().all()
        if existing and not force:
            raise SystemExit(
                f"REFUSING: {len(existing)} recipe(s) already imported "
                f"(same source_url), e.g. {existing[0]}. Re-run with "
                "--force to delete and re-import them, or use a fresh DB.")
        if existing and force:
            conn.execute(
                text("DELETE FROM community_recipes"
                     " WHERE source_url = ANY(:urls)"),
                {"urls": existing},
            )
            stats["warnings"].append(
                f"--force deleted {len(existing)} existing recipe(s)")
        for recipe, language in jobs:
            row = build_recipe_row(recipe, language)
            if language == "zh":
                raw_cook = recipe.get("cook_time")
                if raw_cook not in (None, "") \
                        and raw_cook not in COOK_TIME_MAP:
                    stats["warnings"].append(
                        f"unknown cook_time {raw_cook!r} for "
                        f"{row['slug']}: stored NULL")
                stats["cook_time"][str(row["cook_time"])] += 1
            else:
                stats["cook_time"]["None"] += 1
            recipe_id = conn.execute(
                text("INSERT INTO community_recipes (author_id, title,"
                     " cover_image, steps_json, cook_time, status,"
                     " description, source_url, category, language,"
                     " difficulty, taste, slug, author)"
                     " VALUES (NULL, :title, :cover_image,"
                     " CAST(:steps_json AS jsonb), :cook_time,"
                     " 'published', :description, :source_url, :category,"
                     " :language, :difficulty, :taste, :slug, :author)"
                     " RETURNING id"),
                row,
            ).scalar_one()
            stats["recipes"][language] += 1
            mapping.append({
                "id": str(recipe_id),
                "slug": row["slug"],
                "language": language,
                "source_url": row["source_url"],
            })
            is_main_flags = _main_group_map(recipe)
            for line, is_main in zip(recipe.get("ingredients") or [],
                                     is_main_flags):
                raw_name, amount, unit, split_notes = split_ingredient(line)
                if amount is not None and amount > MAX_AMOUNT:
                    stats["warnings"].append(
                        f"amount {amount} over numeric(10,2) for "
                        f"{line!r}: stored NULL")
                    amount = None
                if "rounded to 2dp" in split_notes:
                    stats["rounded_amounts"] += 1
                bucket = ("amount+unit" if (amount is not None and unit)
                          else "amount-only" if amount is not None
                          else "neither")
                stats["buckets"][language][bucket] += 1
                canon = resolve_canonical(raw_name, None, master_map,
                                          alias_map=alias_map)
                if canon is not None:
                    stats["matched"] += 1
                else:
                    stats["unmatched"] += 1
                conn.execute(
                    text("INSERT INTO recipe_ingredients (recipe_id,"
                         " canonical_ingredient_id, raw_name, amount,"
                         " unit, is_main_ingredient)"
                         " VALUES (:rid, :canon, :raw, :amount, :unit,"
                         " :is_main)"),
                    {"rid": recipe_id,
                     "canon": canon["id"] if canon else None,
                     "raw": raw_name, "amount": amount, "unit": unit,
                     "is_main": is_main},
                )
                stats["ingredients"][language] += 1
        if dry_run:
            conn.rollback()
    total_recipes = sum(stats["recipes"].values())
    total_ingredients = sum(stats["ingredients"].values())
    summary = {
        "recipes": dict(stats["recipes"]),
        "recipes_total": total_recipes,
        "ingredients": dict(stats["ingredients"]),
        "ingredients_total": total_ingredients,
        "buckets": {lang: dict(c)
                    for lang, c in stats["buckets"].items()},
        "canonical_matched": stats["matched"],
        "canonical_unmatched": stats["unmatched"],
        "cook_time": dict(stats["cook_time"]),
        "rounded_amounts": stats["rounded_amounts"],
        "warnings": stats["warnings"],
        "dry_run": dry_run,
    }
    if not dry_run and mapping_path is not None:
        payload = {
            "note": ("Generated by the TEST run of scripts/import_recipes.py "
                     "against a scratch database. The uuids below belong "
                     "to THAT database; the eventual live run will produce "
                     "different uuids -- match on source_url, not id."),
            "recipes_total": total_recipes,
            "recipes": mapping,
        }
        Path(mapping_path).write_text(
            json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8")
        summary["mapping_file"] = str(mapping_path)
    return summary


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Import the 186 seed recipes (Option B).")
    parser.add_argument("--vn", default="/tmp/imsf-recipes/monngonmoingay-100.json")
    parser.add_argument("--cn", default="/tmp/imsf-recipes/meishichina-100.json")
    parser.add_argument("--db-url", default=None,
                        help="Defaults to DATABASE_URL env.")
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--force", action="store_true")
    parser.add_argument("--mapping-out", default=None,
                        help="Defaults to scripts/recipe_id_mapping.json")
    args = parser.parse_args(argv)
    import os
    db_url = args.db_url or os.environ.get("DATABASE_URL")
    if not db_url:
        raise SystemExit("No --db-url and no DATABASE_URL env var.")
    mapping_path = args.mapping_out
    if mapping_path is None and not args.dry_run:
        mapping_path = str(Path(__file__).resolve().parent
                           / "recipe_id_mapping.json")
    summary = run_import(args.vn, args.cn, db_url, dry_run=args.dry_run,
                         force=args.force, mapping_path=mapping_path)
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
