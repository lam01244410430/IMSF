#!/usr/bin/env node
/**
 * Sinh tokens.css + nutui.css từ src/ui/tokens.ts (nguồn chân lý duy nhất).
 * Design doc §3.5: zero-dependency; chạy ở `npm run theme:build`, CI chạy
 * `npm run theme:check` (fail nếu output sinh ra khác file đã commit).
 *
 * Node 22 type-strips tokens.ts nên import trực tiếp được (tokens.ts chỉ dùng
 * cú pháp TypeScript "erasable").
 *
 * Mapping NutUI (§3.6) đã hiệu chỉnh theo Gate 0 (kiểm chứng trên
 * @nutui/nutui-react-taro@3.0.20 đã cài, dist/styles/variables.scss):
 * - onSurfaceVariant -> --nutui-color-text-help (KHÔNG có
 *   --nutui-color-text-secondary trong 3.0.20).
 * - cỡ chữ gốc -> --nutui-font-size-base (KHÔNG có --nutui-base-font-size).
 * - radius -> --nutui-button-border-radius (KHÔNG có
 *   --nutui-border-radius-base).
 * - KHÔNG sinh --nutui-color-primary-light (không tồn tại; chỉ có
 *   --nutui-color-primary-light-pressed).
 * - KHÔNG sinh --nutui-font-family (chỉ là SCSS var, không phải CSS var);
 *   font stack đặt trên :root trong tokens.css để NutUI kế thừa.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const { tokens } = await import(join(root, 'src', 'ui', 'tokens.ts'))

const c = tokens.color
const s = tokens.shape

/** [tên biến CSS, giá trị] cho tokens.css (namespace --imsf-*). */
const imsfVars = [
  ['--imsf-color-primary', c.primary],
  ['--imsf-color-on-primary', c.onPrimary],
  ['--imsf-color-primary-container', c.primaryContainer],
  ['--imsf-color-on-primary-container', c.onPrimaryContainer],
  ['--imsf-color-secondary', c.secondary],
  ['--imsf-color-secondary-container', c.secondaryContainer],
  ['--imsf-color-error', c.error],
  ['--imsf-color-error-container', c.errorContainer],
  ['--imsf-color-warning', c.warning],
  ['--imsf-color-warning-container', c.warningContainer],
  ['--imsf-color-surface', c.surface],
  ['--imsf-color-background', c.background],
  ['--imsf-color-surface-variant', c.surfaceVariant],
  ['--imsf-color-outline', c.outline],
  ['--imsf-color-on-surface', c.onSurface],
  ['--imsf-color-on-surface-variant', c.onSurfaceVariant],
  ['--imsf-color-info', c.info],
  ['--imsf-color-info-light', c.infoLight],
  ['--imsf-color-info-dark', c.infoDark],
  ['--imsf-color-text-disabled', c.textDisabled],
  ['--imsf-color-divider', c.divider],
  ['--imsf-font-family', tokens.font.family],
  ['--imsf-font-size-base', `${tokens.font.baseSize}px`],
  ['--imsf-radius-base', `${s.base}px`],
  ['--imsf-radius-button', `${s.button}px`],
  ['--imsf-radius-button-small', `${s.buttonSmall}px`],
  ['--imsf-radius-card', `${s.card}px`],
  ['--imsf-radius-text-field', `${s.textField}px`],
  ['--imsf-radius-chip', `${s.chip}px`],
  ['--imsf-radius-dialog', `${s.dialog}px`],
  ['--imsf-radius-toast', `${s.toast}px`],
  ['--imsf-radius-skeleton', `${s.skeleton}px`],
  ['--imsf-spacing-unit', `${tokens.spacing.unit}px`],
  ['--imsf-header-height', `${tokens.size.headerHeight}px`],
  ['--imsf-nav-height', `${tokens.size.navHeight}px`],
  ['--imsf-fab-size', `${tokens.size.fab}px`],
  ['--imsf-z-bottom-navigation', String(tokens.zIndex.bottomNavigation)],
  ['--imsf-z-fab', String(tokens.zIndex.fab)],
  ['--imsf-z-drawer', String(tokens.zIndex.drawer)],
  ['--imsf-z-modal', String(tokens.zIndex.modal)],
  ['--imsf-z-snackbar', String(tokens.zIndex.snackbar)],
  ['--imsf-z-tooltip', String(tokens.zIndex.tooltip)],
]

/** [tên biến CSS, giá trị] cho nutui.css (override NutUI, §3.6 + Gate 0). */
const nutuiVars = [
  ['--nutui-color-primary', c.primary],
  ['--nutui-color-primary-stop-1', c.primaryDark],
  ['--nutui-color-primary-stop-2', c.primaryDark],
  ['--nutui-color-primary-pressed', c.primaryDark],
  ['--nutui-color-primary-disabled', c.primaryContainer],
  ['--nutui-color-text', c.onSurface],
  // Gate 0: slot text phụ của NutUI 3.0.20 là --nutui-color-text-help.
  ['--nutui-color-text-help', c.onSurfaceVariant],
  ['--nutui-color-text-disabled', c.textDisabled],
  ['--nutui-color-border', c.divider],
  ['--nutui-color-background', c.background],
  ['--nutui-font-size-base', `${tokens.font.baseSize}px`],
  ['--nutui-button-border-radius', `${s.button}px`],
  ['--nutui-cell-padding', tokens.nutui.cellPadding],
  ['--nutui-color-danger', c.error],
  ['--nutui-color-warning', c.warning],
  ['--nutui-color-success', c.primary],
  // D-F1: token info chờ Lam duyệt; chưa component nào dùng.
  ['--nutui-color-info', c.info],
]

function render(vars, header) {
  const lines = vars.map(([name, value]) => `  ${name}: ${value};`)
  return `${header}\n:root {\n${lines.join('\n')}\n}\n`
}

const header =
  '/* DO NOT EDIT — generated by scripts/build-tokens.mjs from src/ui/tokens.ts (design doc §3.5). */'

const tokensCss =
  render(imsfVars, header) +
  '\n:root {\n' +
  `  font-family: ${tokens.font.family};\n` +
  `  font-size: ${tokens.font.baseSize}px;\n` +
  '}\n'

const nutuiCss = render(nutuiVars, header)

const targets = [
  [join(root, 'src', 'ui', 'tokens.css'), tokensCss],
  [join(root, 'src', 'ui', 'nutui.css'), nutuiCss],
]

const check = process.argv.includes('--check')
let failed = false
for (const [path, content] of targets) {
  if (check) {
    let current = ''
    try {
      current = readFileSync(path, 'utf8')
    } catch {
      current = ''
    }
    if (current !== content) {
      console.error(`theme:check FAILED — ${path} is out of date. Run \`npm run theme:build\`.`)
      failed = true
    } else {
      console.log(`theme:check OK — ${path}`)
    }
  } else {
    writeFileSync(path, content)
    console.log(`wrote ${path}`)
  }
}
if (failed) process.exit(1)
