"""Application ports. Infrastructure owns SQL; use cases own transactions."""
from typing import Protocol
from app.finance.domain import Actor, HouseholdContext
from app.finance.dto import TransactionPost


class HouseholdAccess(Protocol):
    async def resolve(self, actor: Actor, household_id: int, permission: str, *, write: bool) -> HouseholdContext: ...


class FinanceRepository(Protocol):
    async def product(self, household_id: int, identifier: int) -> dict | None: ...
    async def currencies(self) -> list[dict]: ...
    async def currency(self, code: str) -> dict | None: ...
    async def get(self, resource: str, household_id: int, identifier: int, *, lock: bool = False) -> dict | None: ...
    async def page(self, resource: str, household_id: int, limit: int, cursor: list | None, filters: dict) -> list[dict]: ...
    async def items(self, household_id: int, transaction_id: int) -> list[dict]: ...
    async def create(self, resource: str, values: dict) -> dict: ...
    async def update(self, resource: str, household_id: int, identifier: int, values: dict) -> dict: ...
    async def transaction_result(self, household_id: int, transaction_id: int) -> dict: ...
    async def payments(self, household_id: int, transaction_id: int) -> list[dict]: ...
    async def ledger_entries(self, household_id: int, transaction_id: int) -> list[dict]: ...
    async def has_entries(self, household_id: int, account_id: int) -> bool: ...
    async def ledger(self, household_id: int, account_id: int | None, date_from, date_to, position, limit: int) -> list[dict]: ...
    async def balance(self, household_id: int, account_id: int, as_of=None, position=None) -> dict: ...
    async def reserve(self, values: dict) -> tuple[int, dict | None]: ...
    async def complete(self, identifier: int, status: int, body: dict | None) -> None: ...
    async def audit(self, values: dict) -> None: ...

    async def reconciliation_rows(self, household_id: int, resource: str) -> list[dict]: ...
    async def reconciliation_anchor(self, household_id: int, account_id: int, currency_code: str) -> dict | None: ...
    async def reconciliation_open(self, household_id: int, account_id: int) -> int | None: ...
    async def reconciliation_cutoff(self, household_id: int, account_id: int) -> int | None: ...


