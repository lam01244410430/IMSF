"""P04-OPEN-07/13 proposed ports. Services own UoWs; repositories only flush."""

from typing import Protocol


class InventoryRepository(Protocol):
    async def get(self, resource, hid, identifier, *, lock=False) -> dict | None: ...
    async def create(self, resource, values) -> dict: ...
    async def update(self, resource, hid, identifier, values) -> dict: ...
    async def page(self, resource, hid, limit, position, filters) -> list[dict]: ...
    async def lock_products(self, hid, identifiers) -> list[dict]: ...
    async def lock_lots(self, hid, product_ids) -> list[dict]: ...
    async def lock_purchase(self, hid, item_id) -> dict | None: ...
    async def lock_purchases(self, hid, item_ids) -> dict: ...
    async def negative_kinds(self, hid, lot_id) -> list[str]: ...
    async def create_refund_link(self, values) -> dict: ...
    async def receipt_id(self, hid, lot_id) -> int: ...
    async def factor(self, source, target): ...
    async def unit(self, identifier) -> dict | None: ...
    async def split_received(self, hid, item_id): ...
    async def has_history(self, hid, product_id) -> bool: ...


class CommandRecords(Protocol):
    async def reserve(self, values) -> tuple[int, dict | None]: ...
    async def complete(self, identifier, status, body) -> None: ...
    async def audit(self, values) -> None: ...
