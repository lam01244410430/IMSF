"""Lifecycle read and expiry-job ports. No stock mutation capability."""
from datetime import date
from typing import Protocol


class LifecycleRepository(Protocol):
    async def lot_page(self, hid: int, limit: int, position: int | None,
                       filters: dict, local_date: date) -> list[dict]: ...
    async def alert_page(self, hid: int, limit: int, position: int | None,
                         filters: dict) -> list[dict]: ...
    async def alert(self, hid: int, identifier: int) -> dict | None: ...


class ExpiryJobRepository(Protocol):
    """PROPOSAL OPEN-04/05/08: no commits and no stock-writing capability."""
    async def active_households(self, after_id: int, limit: int) -> list[int]: ...
    async def lock_household(self, hid: int) -> dict | None: ...
    async def timezone(self, hid: int) -> object: ...
    async def valid_timezone(self, name: str) -> bool: ...
    async def enqueue(self, hid: int, local_date: date, timezone: str) -> dict: ...
    async def job(self, hid: int, identifier: int, *, lock: bool = False) -> dict | None: ...
    async def claim_due(self, job_id: int | None) -> dict | None: ...
    async def now(self): ...
    async def update_claim(self, row: dict, token: str) -> dict: ...
    async def abandon_exhausted(self, row: dict) -> None: ...
    async def high_water(self, hid: int) -> int: ...
    async def source_page(self, hid: int, last: int, high: int, limit: int) -> list[dict]: ...
    async def insert_alert(self, values: dict) -> int: ...
    async def fenced_update(self, hid: int, identifier: int, token: str, **values) -> dict | None: ...
